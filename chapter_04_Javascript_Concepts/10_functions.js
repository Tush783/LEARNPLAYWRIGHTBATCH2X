//Defining a function
function greet()
{
    console.log("Hello, How are you?");
}

//Calling the function
greet(); // Output: Hello, How are you?
greet(); // Output: Hello, How are you?
greet(); // Output: Hello, How are you?

//Functions are reusable blocks of code that perform a specific task. 
// They allow you to organize your code and avoid repetition by defining a set of instructions that can be executed 
// whenever needed. 
// In this example, the function 'greet' is defined to print a greeting message, 
// and it is called multiple times to display the message each time.


