let single = 'Hello World';
let double = "Hi world";
console.log(single); // Output: Hello World
console.log(double); // Output: Hi world    
console.log(typeof single); // Output: "string"
console.log(typeof double); // Output: "string"

//double quotes can contain inside single quotes without escaping
let singleWithDouble = 'She said, "Hello!"';
console.log(singleWithDouble); // Output: She said, "Hello!"

//there is no concept of character in JavaScript, so we can use single or double quotes for strings
let char = 'A';
console.log(char); // Output: A 
console.log(typeof char); // Output: "string"

//JavaScript prefer to use String

