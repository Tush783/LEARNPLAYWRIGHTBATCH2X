// % = Modulus operator
let x = 10, y = 3; // Declare two variables x and y with values 10 and 3 respectively
let remainder = x % y; // Modulus operator gives the remainder of the division of x by y
console.log(remainder); // Output: 1 (because 10 divided by 3 is 3 with a remainder of 1)

let result = 13 % 7;
console.log(result); // Output: 6 (because 13 divided by 7 is 1 with a remainder of 6)

console.log(20 % 4); // Output: 0 (because 20 divided by 4 is 5 with no remainder)
console.log(15 % 6); // Output: 3 (because 15 divided by 6 is 2 with a remainder of 3)
console.log(9 % 2); // Output: 1 (because 9 divided by 2 is 4 with a remainder of 1)