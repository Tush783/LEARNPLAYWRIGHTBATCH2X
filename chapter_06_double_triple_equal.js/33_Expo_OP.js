console.log(2 ** 3); // Output: 8 (because 2 raised to the power of 3 is 8)

let x =10;
let y = 3;
console.log(x ** y); // Output: 1000 (because 10 raised to the power of 3 is 1000)

console.log(5 ** 0); // Output: 1 (because any number raised to the power of 0 is 1)
console.log(7 ** 1); // Output: 7 (because any number raised to the power of 1 is itself)