// && --> AND GATE
// || --> OR GATE

let a = true;
let b = false;
console.log(a && b); // false -> both a and b need to be true for this to be true
console.log(a || b); // true  -> at least one of a or b needs to be true for this to be true
console.log(!a);    // false -> negation of a, which is true, so it becomes false
console.log(!b);    // true  -> negation of b, which is false, so it becomes true