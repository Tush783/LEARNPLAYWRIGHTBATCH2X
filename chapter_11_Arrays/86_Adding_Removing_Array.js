let arr = [1,2,3];
console.log(arr);

//ADD TO THE END
arr.push(4);
console.log(arr);

//REMOVE FROMT THE END OF THE ARRAY
arr.pop(4);
console.log(arr);

//PUSHING MULTIPLE ELEMENT TO THE ARRAY
arr.push(5,6);
console.log(arr);

//ADD TO THE BEGINNING OF THE ARRAY
arr.unshift(0);
console.log(arr);

//REMOVE FROM THE BEGINNING OF THE ARRAY
arr.shift();
console.log(arr);
